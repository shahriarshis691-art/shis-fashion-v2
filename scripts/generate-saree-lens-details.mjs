async function fileExists(path) {
  try {
    await access(path, fsConstants.F_OK)
    return true
  } catch {
    return false
  }
}

function clamp(value, min, max) {
  return Math.max(min, Math.min(max, value))
}

function extractPortrait(width, height, centerX, centerY, fraction = 0.50) {
  let cropHeight = Math.round(Math.min(height, (width * 4) / 3) * fraction)
  let cropWidth = Math.round((cropHeight * 3) / 4)

  if (cropWidth > width) {
    cropWidth = width
    cropHeight = Math.min(height, Math.round((cropWidth * 4) / 3))
  }
  if (cropHeight > height) {
    cropHeight = height
    cropWidth = Math.min(width, Math.round((cropHeight * 3) / 4))
  }

  const left = Math.round(clamp(centerX * width - cropWidth / 2, 0, width - cropWidth))
  const top = Math.round(clamp(centerY * height - cropHeight / 2, 0, height - cropHeight))
  return { left, top, width: cropWidth, height: cropHeight }
}

async function writeCrop(sourcePath, box, outputPath) {
  const longest = Math.max(box.width, box.height)
  const pipeline = sharp(sourcePath).extract(box)

  if (longest > MAX_EDGE) {
    pipeline.resize(MAX_EDGE, MAX_EDGE, {
      fit: 'inside',
      withoutEnlargement: true,
      kernel: sharp.kernel.lanczos3,
    })
  }

  await pipeline.jpeg({ quality: 92, mozjpeg: true, chromaSubsampling: '4:4:4' }).toFile(outputPath)
}

async function writeGeneratedTs(detailMap) {
  const lines = [
    '/** Auto-generated by scripts/generate-saree-lens-details.mjs — do not edit manually. */',
    'export const SAREE_LENS_DETAIL_IMAGES: Record<string, string[]> = {',
  ]

  for (const slug of Object.keys(detailMap).sort()) {
    const paths = detailMap[slug]
    if (!paths?.length) {
      continue
    }
    lines.push(`  '${slug}': [${paths.map((path) => `'${path}'`).join(', ')}],`)
  }

  lines.push('}', '')
  await writeFile(GENERATED_TS, lines.join('\n'), 'utf8')
}

async function main() {
  await mkdir(OUTPUT_DIR, { recursive: true })
  const detailMap = {}

  for (const entry of NUMBERED_PRODUCTS) {
    const source = join(root, 'public', 'saree', entry.file)
    if (!(await fileExists(source))) {
      console.log(`SKIP missing source: ${entry.file}`)
      continue
    }

    const meta = await sharp(source).metadata()
    const width = meta.width ?? 0
    const height = meta.height ?? 0
    if (!width || !height) {
      console.log(`SKIP unreadable: ${entry.file}`)
      continue
    }

    const crops = [
      { index: 1, box: extractPortrait(width, height, entry.texture[0], entry.texture[1]) },
      { index: 2, box: extractPortrait(width, height, entry.border[0], entry.border[1]) },
    ]

    const saved = []
    for (const crop of crops) {
      const destName = `${entry.slug}-detail-${crop.index}.jpg`
      const dest = join(OUTPUT_DIR, destName)
      await writeCrop(source, crop.box, dest)
      saved.push(`${PUBLIC_PREFIX}/${destName}`)
      console.log(`${entry.slug} detail-${crop.index}: ${crop.box.width}x${crop.box.height}`)
    }

    if (saved.length) {
      detailMap[entry.slug] = saved
    }
  }

  await writeGeneratedTs(detailMap)
  console.log(`Updated src/data/sareeLensDetails.generated.ts (${Object.keys(detailMap).length} products)`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
